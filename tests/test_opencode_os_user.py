async def test_kill_tree_running_proc_exact_sequence(make_config):
    sl, probe, _ = launcher(make_config)
    proc = FakeProc(777)
    events: list[tuple] = []
    orig_run, orig_killpg = probe.run, probe.killpg

    async def run(argv, *, timeout_s):
        events.append(("run", tuple(argv[5:])))
        return await orig_run(argv, timeout_s=timeout_s)

    def killpg(pgid, sig):
        events.append(("killpg", pgid, sig))
        orig_killpg(pgid, sig)

    probe.run, probe.killpg = run, killpg  # type: ignore[method-assign]
    await sl.kill_tree(proc, grace_s=0.5)  # type: ignore[arg-type]
    assert events == [
        ("killpg", 777, "TERM"),
        ("run", (PKILL, "-TERM", "-s", "777")),
        ("run", (PKILL, "-KILL", "-s", "777")),
        ("killpg", 777, "KILL"),
    ]
    assert proc.killed == 0


