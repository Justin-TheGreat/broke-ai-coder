class FakeHostProbe:
    def __init__(self) -> None:
        self.runs: list[list[str]] = []
        self.killpgs: list[tuple[int, str]] = []
        self.results: dict[tuple[str, ...], ProbeResult] = {}
        self.raise_on_run = False
        self._platform = "linux"
        self._euid = 1000
        self._pid = 4242
        self.users: dict[str, UserInfo] = {"justin": DAEMON, "brokeoc": OC}
        self.groups: frozenset[str] = frozenset({"brokeoc", "brokeai"})
        self.interop = False
        self.dirs: set[str] = set()

    def platform(self) -> str:
        return self._platform

    def euid(self) -> int:
        return self._euid

    def pid(self) -> int:
        return self._pid

    def user_by_uid(self, uid: int) -> UserInfo | None:
        return next((u for u in self.users.values() if u.uid == uid), None)

    def user_by_name(self, name: str) -> UserInfo | None:
        return self.users.get(name)

    def group_names(self, user: UserInfo) -> frozenset[str]:
        return self.groups

    def interop_enabled(self) -> bool:
        return self.interop

    def is_dir(self, path: str) -> bool:
        return path in self.dirs

    def killpg(self, pgid: int, sig: str) -> None:
        self.killpgs.append((pgid, sig))

    async def run(self, argv: Sequence[str], *, timeout_s: float) -> ProbeResult:
        self.runs.append(list(argv))
        if self.raise_on_run:
            raise RuntimeError("probe exploded")
        key = tuple(argv)
        if key in self.results:
            return self.results[key]
        inner = list(argv[5:])  # after sudo -n -u name --
        if inner and inner[0] == TEST:
            flag, path = inner[1], inner[2]
            # -r/-e: not accessible (isolation holds). -w: writable. -x: allowed except the
            # daemon home. Tests override single probes with set().
            if flag == "-w" or (flag == "-x" and path != self.users["justin"].home):
                return ProbeResult(0)
            return ProbeResult(1)
        return ProbeResult(0)

    def set(self, inner: list[str], result: ProbeResult) -> None:
        self.results[(SUDO, "-n", "-u", "brokeoc", "--", *inner)] = result

    @property
    def pkills(self) -> list[list[str]]:
        return [r[5:] for r in self.runs if r[5:6] == [PKILL]]


class FakeProc:
    def __init__(self, pid: int = 777, *, returncode: int | None = None, exits: bool = True):
        self.pid = pid
        self.returncode = returncode
        self._exits = exits
        self.killed = 0

    async def wait(self) -> int:
        if self.returncode is None:
            if not self._exits:
                await asyncio.sleep(3600)
            self.returncode = -15
        return self.returncode

    def kill(self) -> None:
        self.killed += 1
        self.returncode = -9


def launcher(make_config, probe: FakeHostProbe | None = None, **oc):
    opencode = {
        "os_user": {"mode": "sudo"},
        "command": [EXE],
        "server_directory": "/var/lib/broke-ai-coder/opencode-server",
        **oc,
    }
    cfg = make_config(opencode=opencode)
    p = probe or FakeHostProbe()
    return SudoLauncher(cfg, probe=p), p, cfg


