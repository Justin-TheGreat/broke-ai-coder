def _failing(probe: FakeHostProbe, case: str) -> dict:
    """Mutate the fake for one failing check; return opencode config overrides."""
    oc: dict = {}
    if case == "platform":
        probe._platform = "win32"
    elif case == "root":
        probe._euid = 0
    elif case == "no_daemon":
        probe._euid = 555
    elif case == "no_user":
        del probe.users["brokeoc"]
    elif case == "same_uid":
        probe.users["brokeoc"] = UserInfo("brokeoc", 1000, 1000, "/home/brokeoc")
    elif case == "uid0":
        probe.users["brokeoc"] = UserInfo("brokeoc", 0, 0, "/root")
    elif case == "group":
        probe.groups = frozenset({"sudo", "docker", "brokeoc"})
    elif case == "relative_cmd":
        oc["command"] = ["opencode"]
    elif case == "cmd_in_home":
        oc["command"] = ["/home/justin/bin/opencode"]
    elif case == "passthrough":
        oc["env_passthrough"] = ["FOO"]
    elif case == "serverdir_relative":
        oc["server_directory"] = "data/opencode-server"
    elif case == "serverdir_in_home":
        oc["server_directory"] = "/home/justin/serve"
    elif case == "interop":
        probe.interop = True
    elif case == "version":
        probe.set([EXE, "--version"], ProbeResult(1, b"", b"sudo: a password is required\n"))
    elif case == "access_home_r":
        probe.set([TEST, "-r", "/home/justin"], ProbeResult(0))
    elif case == "access_home_x":
        probe.set([TEST, "-x", "/home/justin"], ProbeResult(0))
    elif case == "access_secrets":
        probe.set([TEST, "-r", "/home/justin/.config/broke-ai-coder/secrets.env"], ProbeResult(0))
    elif case == "access_mntc":
        probe.set([TEST, "-r", "/mnt/c"], ProbeResult(0))
    elif case == "access_proc":
        probe.set([TEST, "-r", "/proc/4242/environ"], ProbeResult(0))
    elif case == "access_other_rc":
        probe.set([TEST, "-r", "/home/justin"], ProbeResult(2))
    elif case == "access_none":
        probe.set([TEST, "-r", "/home/justin"], ProbeResult(None))
    elif case == "server_dir_w":
        probe.set([TEST, "-w", "/srv/oc"], ProbeResult(1))
        oc["server_directory"] = "/srv/oc"
    elif case == "server_dir_x":
        probe.set([TEST, "-x", "/srv/oc"], ProbeResult(1))
        oc["server_directory"] = "/srv/oc"
    return oc


def _prepare(case: str, make_config):
    probe = FakeHostProbe()
    oc = _failing(probe, case)
    return launcher(make_config, probe, **oc)


